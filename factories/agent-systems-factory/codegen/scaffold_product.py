    violations: list[str] = []
    if END not in reachable_from_start:
        violations.append("__end__ is unreachable from __start__")
    for node in sorted(nodes):
        if node == START:
            continue
        if node not in reachable_from_start:
            violations.append(f"node {node!r} is unreachable from __start__")
        if node != END and node not in can_reach_end:
            violations.append(f"node {node!r} cannot reach __end__ (orphan/dead-end)")
    return violations
