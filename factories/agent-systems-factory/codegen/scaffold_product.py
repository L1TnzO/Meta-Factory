def _topology_fn(topo: dict, channels: list) -> tuple[str, str]:
    """Source de un builder de topología declarada + su entrada en el registro. Reusa GeneratedPromptNode
    (los mismos nodos instrumentados del producto); estructura derivada del blueprint (nodes/edges)."""
    name = topo["name"]
    fn = f"build_{name}_graph"
    interrupt_at = topo.get("interrupt_at", "")
    instr_const = f"_{name.upper()}_INSTRUCTIONS"
    chtype = {c["id"]: c.get("type", "str") for c in channels}
    instr_lines: list[str] = []
    add_node_lines: list[str] = []
    for n in topo["nodes"]:
        nid = n["id"]
        instr = str(n.get("instruction", f"You are the '{nid}' stage of an agent.")).replace('"', '\\"')
        instr_lines.append(f'    "{nid}": "{instr}",')
        wt = n.get("writes_to")
        if wt:
            is_list = chtype.get(wt) == "list"
            add_node_lines.append(
                f'    builder.add_node("{nid}", GeneratedPromptNode("{nid}", {instr_const}["{nid}"], '
                f'writes_to="{wt}", writes_is_list={is_list}))')
        else:
            add_node_lines.append(
                f'    builder.add_node("{nid}", GeneratedPromptNode("{nid}", {instr_const}["{nid}"]))')
    add_edge_lines: list[str] = []
    for src, dst in topo["edges"]:
        s = "START" if src == "__start__" else f'"{src}"'
        d = "END" if dst == "__end__" else f'"{dst}"'
        add_edge_lines.append(f"    builder.add_edge({s}, {d})")
    src_code = (
        f"{instr_const}: dict[str, str] = {{\n" + "\n".join(instr_lines) + "\n}\n\n\n"
        f"def {fn}(checkpointer: Any = None) -> Any:\n"
        f'    """Topología \'{name}\' declarada en el blueprint (B-3, breadth)."""\n'
        f"    from langgraph.checkpoint.memory import MemorySaver\n\n"
        f"    builder: Any = StateGraph(AgentState)   # Any: el nodo concreto destraba el type-var de add_node\n"
        + "\n".join(add_node_lines) + "\n"
        + "\n".join(add_edge_lines) + "\n"
        f"    cp = checkpointer if checkpointer is not None else MemorySaver()\n"
        f'    return builder.compile(checkpointer=cp, interrupt_before=["{interrupt_at}"])\n'
    )
    return src_code, f'    "{name}": {fn},'


def _topologies_module(bp: dict) -> str:
    """topologies.py: el registro de topologías. 'linear' = build_graph (la canónica que usa el producto);
    cada topología declarada en domain.product.topologies suma un builder + entrada en TOPOLOGIES."""
    pkg = bp["package_name"]
    channels = bp["channels"]
    topos = bp.get("topologies", []) or []
    builders: list[str] = []
    registry: list[str] = []
    for topo in topos:
        s, e = _topology_fn(topo, channels)
        builders.append(s)
        registry.append(e)
    body = _R(_TOPOLOGIES_HEADER, PKG=pkg)
    body += "\n\n".join(builders)
    body += "\n\nTOPOLOGIES: dict[str, Callable[..., Any]] = {\n"
    body += '    "linear": build_graph,\n'
    if registry:
        body += "\n".join(registry) + "\n"
    body += "}\n"
    return body


