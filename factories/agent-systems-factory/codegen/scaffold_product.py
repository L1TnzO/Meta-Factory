def _state_lines(channels: list) -> str:
    out: list[str] = []
    for ch in channels:
        cid, ctype, reducer = ch["id"], ch.get("type", "str"), ch.get("reducer", "last")
        if reducer == "append":
            out.append(f"    {cid}: Annotated[list[Any], operator.add]")
        else:
            out.append(f"    {cid}: {'list[Any]' if ctype == 'list' else ctype}")
    return "\n".join(out)


def _instructions_block(nodes: list) -> str:
    out: list[str] = []
    for n in nodes:
        if n.get("provision") != "prompt":
            continue
        instr = str(n.get("instruction", f"You are the '{n['id']}' stage of an agent.")).replace('"', '\\"')
        out.append(f'    "{n["id"]}": "{instr}",')
    return "\n".join(out)


def _registry_block(nodes: list, channels: list) -> str:
    chtype = {c["id"]: c.get("type", "str") for c in channels}
    out: list[str] = []
    for n in nodes:
        if n.get("provision") != "prompt":
            continue
        nid, wt = n["id"], n.get("writes_to")
        if wt:
            is_list = chtype.get(wt) == "list"
            out.append(f'    registry["{nid}"] = GeneratedPromptNode("{nid}", _INSTRUCTIONS["{nid}"], '
                       f'writes_to="{wt}", writes_is_list={is_list})')
        else:
            out.append(f'    registry["{nid}"] = GeneratedPromptNode("{nid}", _INSTRUCTIONS["{nid}"])')
    return "\n".join(out)


def _add_nodes_block(nodes: list) -> str:
    return "\n".join(f'    builder.add_node("{n["id"]}", registry["{n["id"]}"])' for n in nodes)


def _add_edges_block(edges: list) -> str:
    out: list[str] = []
    for src, dst in edges:
        s = "START" if src == "__start__" else f'"{src}"'
        d = "END" if dst == "__end__" else f'"{dst}"'
        out.append(f"    builder.add_edge({s}, {d})")
    return "\n".join(out)


