def _bfs(start: str, adjacency: dict[str, list[str]]) -> set[str]:
    """Nodos alcanzables desde `start` siguiendo `adjacency`."""
    seen = {start}
    queue: deque[str] = deque([start])
    while queue:
        node = queue.popleft()
        for nxt in adjacency.get(node, []):
            if nxt not in seen:
                seen.add(nxt)
                queue.append(nxt)
    return seen


