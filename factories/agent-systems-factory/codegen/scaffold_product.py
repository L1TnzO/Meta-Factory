def main(argv: list[str]) -> int:
    root = Path(os.environ.get("METAFACTORY_ROOT", ".")).resolve()
    bp = _load_blueprint(root)
    files = build_files(bp)
    if "--selftest" in argv:
        print(f"scaffold selftest OK: blueprint paquete={bp['package_name']} "
              f"nodos={len(bp['nodes'])} canales={len(bp['channels'])} → {len(files)} archivos")
        return 0
    out = root / "build" / "product"
    for rel, content in files.items():
        dest = out / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(content, encoding="utf-8")
    # MANIFEST AL FINAL: es el keystone del slot generate (dest); su existencia == scaffolder completó.
    (out / "MANIFEST.txt").write_text(
        "# producto LangGraph generado por scaffold_product.py (F1)\n" + "\n".join(sorted(files)) + "\n",
        encoding="utf-8")
    print(f"scaffold: {len(files)} archivos emitidos en {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
