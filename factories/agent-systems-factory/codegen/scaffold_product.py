class GeneratedPromptNode(InstrumentedNodeBase):
    """Level-A prompt node: a model invocation with a factory-written instruction."""

    def __init__(self, node_id: str, instruction: str, writes_to: str | None = None,
                 writes_is_list: bool = False) -> None:
        self.node_id = node_id
        self._instruction = instruction
        self._writes_to = writes_to
        self._writes_is_list = writes_is_list

    def _provision(self) -> str:
        return "prompt"

    def _execute(self, state: dict[str, Any]) -> dict[str, Any]:
        from langchain_core.messages import HumanMessage, SystemMessage

        response = _get_llm().invoke(
            [SystemMessage(content=self._instruction),
             HumanMessage(content=self._render_blackboard(state))]
        )
        content = getattr(response, "content", str(response))
        if self._writes_to is not None:
            value: Any = [content] if self._writes_is_list else content
            return {self._writes_to: value}
        return {f"{self.node_id}__output": content}

    @staticmethod
    def _render_blackboard(state: dict[str, Any]) -> str:
        """Fold the shared blackboard into the prompt so a node SEES the upstream contributions."""
        seed = str(state.get("input_text", ""))
        parts: list[str] = [seed] if seed else []
        for key in sorted(state):
            if key == "input_text":
                continue
            value = state[key]
            if not value:
                continue
            body = "\\n\\n".join(str(item) for item in value) if isinstance(value, list) else str(value)
            parts.append(f"## Blackboard channel '{key}'\\n{body}")
        return "\\n\\n".join(parts)


