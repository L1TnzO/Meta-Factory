#!/usr/bin/env python3
"""seed/verifier.py — the frozen trust root: the ONLY writer of verdicts.

STAGE 0 · trust-chain · R3 · stdlib-only (json, hashlib, subprocess, pathlib, os).
Hand-written and hand-audited. NOT generated by the Meta-Factory (a system cannot be
its own root of trust — SELF-IMPROVEMENT §2). Changing this file is a R3 gate.

It computes `passed` from REAL OS exit codes of subprocesses and from nothing else.
It cannot be fooled by a Python object that claims truthiness, a doc that narrates
success, or a hand-edited verdict: it observes exit codes. This is lock #1 of the
anti-rubber-stamp column (column.md).

Line budget (criterion 8 of BOOTSTRAP): this file ≤ 210 lines including this header.
Audited by a fresh-context reviewer; no CRITICAL findings is a release gate.
"""
from __future__ import annotations

import hashlib
import json
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

# ── canonical artifact layout (relative to a factory/repo root) ──────────────
# Re-derivable, gitignored; the pinned verdict (committed) is the honest constant.
PROOF_DIRNAME = ".proof"


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%MZ")


def proof_dir_for(root: Path) -> Path:
    return Path(root) / PROOF_DIRNAME


def proof_path(root: Path, station_id: str) -> Path:
    return proof_dir_for(root) / f"{station_id}.json"


def ledger_path_for(root: Path) -> Path:
    return proof_dir_for(root) / "ledger.json"


def log_dir_for(root: Path) -> Path:
    return proof_dir_for(root) / "logs"


def active_path_for(root: Path) -> Path:
    return proof_dir_for(root) / "active.json"


# ── the trust kernel: passed and proof_sha derive ONLY from exit codes ───────
def recompute_passed(checks: list[dict]) -> bool:
    """passed iff every check ran and every check exited 0. Empty => false
    (a station with no checks is not 'trivially passed' — that was a façade in ASF)."""
    return len(checks) > 0 and all(int(c["exit"]) == 0 for c in checks)


def compute_proof_sha(station_id: str, checks: list[dict]) -> str:
    """A reproducible digest over the semantic outcome: station id + the sorted
    (name, exit) pairs. EXCLUDES timestamps and machine-specific output so that an
    independent runner re-deriving the same outcome computes the same sha (PF-10,
    two-verifier doctrine). A different exit code => a different sha."""
    canonical = {
        "station": station_id,
        "checks": sorted([(str(c["name"]), int(c["exit"])) for c in checks]),
    }
    blob = json.dumps(canonical, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(blob).hexdigest()


def _write_atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def _subprocess_env(root: Path, extra_pythonpath: str | None) -> dict:
    env = dict(os.environ)
    parts = [p for p in (extra_pythonpath, env.get("PYTHONPATH")) if p]
    if parts:
        env["PYTHONPATH"] = os.pathsep.join(parts)
    return env


def verify_station(
    station_id: str,
    checks: list[dict],
    root: Path,
    *,
    pythonpath: str | None = None,
) -> dict:
    """Run each check command as a subprocess, capture the REAL exit code, write the
    proof + full log to disk, and (only if passed) append to the gate ledger.

    checks: [{"name": str, "cmd": [argv, ...]}].  The caller (Stage-1 runner or the
    inherited factory line) resolves station YAML into concrete commands; the verifier
    only ever OBSERVES exit codes — it never trusts a claimed result.
    Returns the proof dict augmented with 'log_path'.
    """
    root = Path(root).resolve()
    env = _subprocess_env(root, pythonpath)
    results: list[dict] = []
    log_chunks: list[str] = [f"# verify station={station_id} root={root} at={utc_now()}\n"]
    for chk in checks:
        cmd = list(chk["cmd"])
        try:
            proc = subprocess.run(cmd, cwd=root, env=env, capture_output=True, text=True)
            rc, out, err = proc.returncode, proc.stdout, proc.stderr
        except (OSError, ValueError, IndexError) as exc:
            # A check that cannot even LAUNCH is, definitionally, not exit-0. Record it as a
            # RED check (exit 127) so a proof is still written and the gate stays shut — never
            # let a missing/typo'd binary throw past the verdict (fail-safe, not fail-open).
            rc, out, err = 127, "", f"check could not launch: {type(exc).__name__}: {exc}"
        results.append({"name": chk["name"], "cmd": cmd, "exit": rc})
        log_chunks.append(
            f"\n## check={chk['name']} exit={rc} cmd={' '.join(cmd)}\n"
            f"--- stdout ---\n{out}\n--- stderr ---\n{err}\n"
        )

    passed = recompute_passed(results)
    proof = {
        "station": station_id,
        "passed": passed,
        "checks": results,
        "computed_at": utc_now(),
        "proof_sha": compute_proof_sha(station_id, results),
        "writer": "seed/verifier.py",
    }

    log_path = log_dir_for(root) / f"{station_id}-{utc_now().replace(':', '')}.log"
    _write_atomic(log_path, "".join(log_chunks))
    _write_atomic(proof_path(root, station_id), json.dumps(proof, indent=2) + "\n")

    if passed:
        _append_ledger(root, station_id, proof["proof_sha"])

    proof["log_path"] = str(log_path)
    return proof


def _append_ledger(root: Path, station_id: str, proof_sha: str) -> None:
    """The gate ledger: append-only record of opened gates. Re-derivable (gitignored);
    custody is NOT the root of trust — re-derivation on a clean clone is (PF-10)."""
    ledger = ledger_path_for(root)
    entries = []
    if ledger.exists():
        try:
            entries = json.loads(ledger.read_text(encoding="utf-8")).get("gates", [])
        except (json.JSONDecodeError, OSError):
            entries = []
    entries = [e for e in entries if e.get("station") != station_id]
    entries.append({"station": station_id, "proof_sha": proof_sha, "opened_at": utc_now()})
    _write_atomic(ledger, json.dumps({"gates": entries}, indent=2) + "\n")


def load_proof(root: Path, station_id: str) -> dict | None:
    p = proof_path(root, station_id)
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None


def gate_recompute_ok(proof: dict) -> tuple[bool, str]:
    """Lock #2: recompute passed AND proof_sha from the proof's own checks and reject
    if the stored verdict disagrees (a hand-edited passed=true is caught here) or if
    it is not passed. Returns (ok, reason)."""
    checks = proof.get("checks", [])
    re_passed = recompute_passed(checks)
    re_sha = compute_proof_sha(proof.get("station", ""), checks)
    if proof.get("proof_sha") != re_sha:
        return False, f"proof_sha mismatch (stored {proof.get('proof_sha','')[:12]} != recomputed {re_sha[:12]})"
    if bool(proof.get("passed")) != re_passed:
        return False, f"passed tampered (stored {proof.get('passed')} != recomputed {re_passed})"
    if not re_passed:
        failing = [c["name"] for c in checks if int(c["exit"]) != 0] or ["<no checks>"]
        return False, "failing checks: " + ", ".join(failing)
    return True, "ok"


# ── CLI: used by hooks (Lock 2 recompute) and for manual audit ───────────────
def _main(argv: list[str]) -> int:
    if len(argv) >= 2 and argv[0] == "recompute":
        proof = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
        ok, reason = gate_recompute_ok(proof)
        print(f"recompute station={proof.get('station')} ok={ok} — {reason}")
        return 0 if ok else 1
    print("usage: verifier.py recompute <proof.json>", file=sys.stderr)
    return 2


if __name__ == "__main__":
    raise SystemExit(_main(sys.argv[1:]))
