#!/usr/bin/env python3
"""v1-reference cross-reference for SMS-v2 snowballing round 1 (SMS-V2-PROTOCOL.md §7.3).

Parses the v1 BibTeX seed list, drops the three methodology-only entries
(Petersen 2008/2015, Kitchenham 2007 — never candidates for the corpus), and
cross-references every remaining work against the merged v1-corpus + the v2
screening sheet. A work is DECIDIDO-V2 when it can be identified via its
normalized arXiv id inside the v2 corpus (and therefore already carries a
screening 'decision'); everything else is CANDIDATO — a v1 reference that has
never been screened under v2 and is a legitimate seed for backward/forward
snowballing (research/harvest/snowball.py).

Only the arXiv identity is used for matching (see bib_arxiv_id()): a bare DOI
on the bib entry (e.g. an SSRN or ACM DOI) is NOT treated as a corpus-match
signal even when a v2 record happens to carry the identical DOI — v1's arXiv
seed list and v2's OpenAlex/Lens harvest are independent sources, and an
incidental DOI coincidence is not evidence the v1 curator actually reviewed
that v2 record. Stdlib only.

Usage:
  python3 v1_candidates.py --bib ../corpus/seeds/v1-references.bib \
      --corpus ../corpus/merged/corpus.jsonl \
      --sheet ../corpus/screening/screening_full.csv \
      --out v1_candidates.csv
"""

import argparse
import csv
import json
import re
import sys
from pathlib import Path

METHOD_KEYS = {"petersen2008sms", "petersen2015sms", "kitchenham2007guidelines"}

ARXIV_DOI_RE = re.compile(r"10\.48550/arxiv\.([^\s]+)", re.IGNORECASE)
DOI_PREFIX_RE = re.compile(r"^https?://doi\.org/", re.IGNORECASE)
VERSION_SUFFIX_RE = re.compile(r"v\d+$", re.IGNORECASE)

ENTRY_START_RE = re.compile(r"^@[A-Za-z]+\{([^,]+),\s*$")
FIELD_RE = re.compile(r"^\s*([A-Za-z]+)\s*=\s*\{(.*)\}\s*,?\s*$")

OUT_FIELDS = [
    "bibkey", "title", "year", "arxiv_id", "doi", "url",
    "in_corpus_key", "v2_decision", "status",
]


def vstrip(arxiv_id: str) -> str:
    """Strip a trailing version suffix ('v2') from an arXiv id."""
    return VERSION_SUFFIX_RE.sub("", (arxiv_id or "").strip())


def strip_braces(s: str) -> str:
    return re.sub(r"[{}]", "", s or "")


def parse_bib(text: str) -> list[tuple[str, dict]]:
    """Parse the simple '@entry{key, field = {value},}' format used by the
    v1 seed bibliography — one field per physical line, entry closed by a
    standalone '}' line. Nested braces inside a value (e.g. '{{ACRONYM}}')
    are preserved raw; callers strip them via strip_braces()."""
    entries: list[tuple[str, dict]] = []
    cur_key: str | None = None
    cur_fields: dict = {}
    for line in text.splitlines():
        m = ENTRY_START_RE.match(line)
        if m:
            if cur_key is not None:
                entries.append((cur_key, cur_fields))
            cur_key = m.group(1).strip()
            cur_fields = {}
            continue
        if line.strip() == "}":
            if cur_key is not None:
                entries.append((cur_key, cur_fields))
            cur_key = None
            cur_fields = {}
            continue
        if cur_key is not None:
            fm = FIELD_RE.match(line)
            if fm:
                cur_fields[fm.group(1).lower()] = fm.group(2)
    if cur_key is not None:
        entries.append((cur_key, cur_fields))
    return entries


def bib_arxiv_id(fields: dict) -> str:
    """The normalized arXiv id a bib entry is identified by, if any: its own
    'eprint' field (archiveprefix=arXiv convention), else an arXiv id
    embedded in an (unlikely but possible) 10.48550/arxiv.<id> 'doi' field."""
    eprint = (fields.get("eprint") or "").strip()
    if eprint:
        return vstrip(eprint)
    doi = DOI_PREFIX_RE.sub("", (fields.get("doi") or "").strip())
    m = ARXIV_DOI_RE.search(doi)
    if m:
        return vstrip(m.group(1))
    return ""


def load_corpus(path: Path) -> list[dict]:
    return [json.loads(ln) for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]


def build_arxiv_index(records: list[dict]) -> dict:
    """arXiv id (lowercased, version-stripped) -> first matching corpus record,
    indexed both by the record's own 'arxiv_id' field and by an arXiv id
    embedded in its 'doi' field of the form 10.48550/arxiv.<id>."""
    idx: dict = {}
    for rec in records:
        aid = vstrip(rec.get("arxiv_id") or "")
        if aid:
            idx.setdefault(aid.lower(), rec)
        doi = DOI_PREFIX_RE.sub("", (rec.get("doi") or "").strip())
        m = ARXIV_DOI_RE.search(doi)
        if m:
            idx.setdefault(vstrip(m.group(1)).lower(), rec)
    return idx


def record_key(rec: dict) -> str:
    """Mirrors research/harvest/download_pdfs.py:record_key() EXACTLY — the
    sheet's 'key' column is generated by this same function over corpus
    records, so a matched corpus record's key is directly sheet-lookupable."""
    for candidate in (rec.get("id"), rec.get("doi"), rec.get("arxiv_id"), rec.get("title")):
        if candidate:
            return re.sub(r"[^A-Za-z0-9._-]+", "_", str(candidate).split("/")[-1])[:120]
    return "unknown"


def load_sheet(path: Path) -> dict:
    with path.open(newline="", encoding="utf-8") as fh:
        return {row["key"]: row for row in csv.DictReader(fh)}


def build_rows(bib_entries: list[tuple[str, dict]], arxiv_index: dict, sheet: dict) -> list[dict]:
    rows = []
    for bibkey, fields in bib_entries:
        if bibkey in METHOD_KEYS:
            continue
        aid = bib_arxiv_id(fields)
        rec = arxiv_index.get(aid.lower()) if aid else None
        status = "CANDIDATO"
        in_corpus_key = ""
        v2_decision = ""
        if rec is not None:
            status = "DECIDIDO-V2"
            in_corpus_key = record_key(rec)
            srow = sheet.get(in_corpus_key)
            if srow is not None:
                v2_decision = srow.get("decision", "")
        rows.append({
            "bibkey": bibkey,
            "title": strip_braces(fields.get("title", "")),
            "year": fields.get("year", ""),
            "arxiv_id": fields.get("eprint", ""),
            "doi": fields.get("doi", ""),
            "url": fields.get("url", ""),
            "in_corpus_key": in_corpus_key,
            "v2_decision": v2_decision,
            "status": status,
        })
    rows.sort(key=lambda r: (0 if r["status"] == "DECIDIDO-V2" else 1, r["bibkey"]))
    return rows


def write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.parent / f".{path.name}.tmp"
    with tmp.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=OUT_FIELDS)
        writer.writeheader()
        for row in rows:
            writer.writerow({k: row.get(k, "") for k in OUT_FIELDS})
    tmp.replace(path)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--bib", required=True, type=Path)
    ap.add_argument("--corpus", required=True, type=Path)
    ap.add_argument("--sheet", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args(argv)

    bib_entries = parse_bib(args.bib.read_text(encoding="utf-8"))
    corpus = load_corpus(args.corpus)
    arxiv_index = build_arxiv_index(corpus)
    sheet = load_sheet(args.sheet)

    rows = build_rows(bib_entries, arxiv_index, sheet)
    write_csv(args.out, rows)

    n_total = len(rows)
    n_decidido = sum(1 for r in rows if r["status"] == "DECIDIDO-V2")
    n_candidato = n_total - n_decidido
    print(f"v1-candidates: {n_total} total, {n_decidido} decidido-v2, {n_candidato} candidato")
    return 0


if __name__ == "__main__":
    sys.exit(main())
