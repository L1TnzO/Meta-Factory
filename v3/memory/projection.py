"""projection — the FIX for G-M1: deterministic projection of FACTS into STATE, PORTED from v2's
`memory/projection.py` (V3-INC5-MEMORY-DOCS, Fase 3).

    python3 -m v3.verify.checks.projection            # the gate; see that module's docstring

This docstring does not spell the legacy package's path, on purpose: `v3.verify.import_boundary`
rule 3 bans naming the v2 substrate under `v3/`, because a string is how a dynamic import or a path
injection hides. Describing what was ported costs nothing; naming the path it came from does.

The lesson this module exists to enforce: a discretionary trigger gets skipped. The cure (ADR-007
§3, ADR-023) is to shrink the surface of JUDGMENT — the more of STATE is a projection of facts
(re-derivable), the less prose the model writes, and the less of it can go stale. What IS
deterministic gets ENFORCED (this block must stay fresh; a gate checks it, hard); the MEANING (which
episode to narrate) stays surfaced, never hard-blocked.

The block projects SLOW facts (the open increment, the RTM per factory) that change at phase
boundaries, not on every turn — minimal churn. FAST facts live in the journal (a live view, ported
separately, out of this slot's scope). NEVER hand-edit the block: it is regenerated by `refresh()`.

Subject UNCHANGED: `START` / `_LEGACY_START` / `END` / `BLOCK_RE` are byte-identical to v2's — the
legacy Spanish START marker is a live migration concern (a `docs/STATE.md` written before ADR-026's
translation still carries it on disk today), not dead code, and the block text below is what
literally lands in `docs/STATE.md`. Same 7-function public surface: `open_increment · rtm_statuses ·
rtm_status · build_block · current_block · is_stale · refresh`.

WHAT CHANGED FROM v2, and why — this port moves the WIRING, never the law:
  - `open_increment` used to delegate to the legacy package's own `_seed.load_seed_lifecycle`; it now
    delegates to `v3.seed_loader.load_seed_lifecycle` (ADDED by this port — this module is that
    loader's first v3 caller; see its own docstring for why it was withheld until now). Same shared
    trust root either way (`seed/lifecycle.py`, at the repo's root, not inside any substrate
    package): a produced factory's inherited `increment_guard` reads a byte-identical copy, so the
    meta and a produced factory enforce the IDENTICAL lifecycle law — this call site does not create
    a second one.
  - `rtm_statuses` used to re-derive the per-factory RTM through the legacy engine's `RunContext` +
    spec loader; it now derives the identical claim through `v3.spec.loader.load_spec`
    (`FactorySpec.requirements`, `Requirement.satisfied_by`) and `v3.seed_loader.load_seed_verifier`
    (`load_proof` / `gate_recompute_ok`) — the SAME law `v3.verify.checks.generality` already uses to
    confirm a station's proof RECOMPUTES green rather than trusting a stored `passed: true` (Lock
    #2). A requirement counts as satisfied only if EVERY station it names in `satisfied_by` loads a
    proof AND that proof recomputes green; never a bare `passed: true` read off disk and trusted.
  - CUT: the `_main(argv)` CLI entrypoint (and the `sys` import it alone needed) — exactly as
    `v3.memory.docs_manifest`'s own port cut its CLI wrapper, for the identical reason. Root
    resolution is now the CALLER's job: `v3.verify.checks.projection` resolves it the way every other
    v3 gate does (default to the repo root, overridable by an optional positional argv). Every
    function here was already root-as-parameter, so nothing about the LAW moved — only a `check|
    refresh` CLI convenience wrapper that was never part of the preserved public surface.
  - the N/A branch for a tree where NO factory has a `.proof/` directory at all (v2 has none — it
    reports "stale vs. the facts" there, which on such a tree is a false positive: the facts simply
    have not been derived yet, not wrongly projected) lives in the GATE, `v3.verify.checks.projection`
    — NOT here. Moving that decision into `is_stale` would change what the law means, and the parity
    oracle below would stop comparing what v2 actually computes.
  - nothing else. `is_stale` / `build_block` / `rtm_statuses` answer byte-for-byte what v2 answered
    on this tree; the retired parity oracle (`corpus_parity`, retired at V3-EXTRACT-CORPUS-PARITY)
    re-derived that every run during the rebuild, comparing the RTM map AND the rendered block AND the
    staleness verdict together — not just the bool, since two laws could agree "not stale" while
    disagreeing about every factory's status, which was exactly the hollow-agreement shape that oracle
    existed to catch.
"""
from __future__ import annotations

import re
from pathlib import Path

START = "<!-- meta:projection (generated from facts; do NOT hand-edit, refreshed by `meta checkpoint`) -->"
_LEGACY_START = "<!-- meta:projection (generado de hechos; NO editar a mano, se refresca con `meta checkpoint`) -->"
END = "<!-- /meta:projection -->"
# Dual-accept the START marker (ADR-026 migration): a STATE.md written before this constant's English
# translation still has the legacy Spanish marker on disk. `refresh()` must FIND that old block to replace
# it in place, not leave it stranded and insert a second one — same lesson as the Estado/Status header
# grammar (ENGLISH-CLI-STRINGS Slot B). `END` never had Spanish words, so it needs no legacy variant.
BLOCK_RE = re.compile(r"(?:" + re.escape(START) + "|" + re.escape(_LEGACY_START) + r")" + r".*?" + re.escape(END),
                      re.DOTALL)


def open_increment(root: Path) -> str | None:
    """Delegates to the seed's lifecycle LAW (`seed/lifecycle.py`) — single source shared with a
    produced factory's inherited `increment_guard`, so the meta and the factory never diverge."""
    from ..seed_loader import load_seed_lifecycle
    return load_seed_lifecycle().open_increment(Path(root))


def rtm_statuses(root: Path) -> dict[str, tuple[str, int, int]]:
    """Re-derives the RTM of every produced factory from artifacts (`.proof/`) — zero narrative.
    STRUCTURED source `{slug: (status, satisfied, total)}` (order = factories sorted). `rtm_status`
    formats it; a fidelity oracle reads it as a deterministic source. Single-source: one proof read
    feeds both the projection and any such oracle."""
    from ..seed_loader import load_seed_verifier
    from ..spec.loader import load_spec

    root = Path(root)
    out: dict[str, tuple[str, int, int]] = {}
    facdir = root / "factories"
    if not facdir.exists():
        return out
    verifier = load_seed_verifier(str(root))
    for fdir in sorted(p for p in facdir.iterdir() if p.is_dir()):
        spec_path = fdir / "factory.spec.yml"
        if not spec_path.exists():
            continue
        spec = load_spec(spec_path)
        total = len(spec.requirements)
        unsat = 0
        for req in spec.requirements:
            ok = bool(req.satisfied_by)
            for sid in req.satisfied_by:
                proof = verifier.load_proof(fdir, sid)
                ok = ok and proof is not None and verifier.gate_recompute_ok(proof)[0]
            if not ok:
                unsat += 1
        status = "COMPLETE" if (unsat == 0 and total > 0) else ("INCOMPLETE" if total > 0 else "—")
        out[spec.slug] = (status, total - unsat, total)
    return out


def rtm_status(root: Path) -> list[str]:
    """The RTM per factory as formatted lines (the projection's view). Derives from `rtm_statuses`."""
    return [f"{slug}: {st} ({sat}/{tot})" for slug, (st, sat, tot) in rtm_statuses(root).items()]


def build_block(root: Path) -> str:
    inc = open_increment(root) or "none"
    rtm = rtm_status(root)
    return "\n".join([
        START,
        "> Fact projection (Tier 0 → STATE). Source: re-derivable artifacts; not narrative.",
        f"- Open increment: {inc}",
        f"- RTM by factory (re-derived from `.proof/`): {' · '.join(rtm) if rtm else 'no factories'}",
        END,
    ])


def current_block(root: Path) -> str | None:
    state = Path(root) / "docs" / "STATE.md"
    if not state.exists():
        return None
    m = BLOCK_RE.search(state.read_text(encoding="utf-8"))
    return m.group(0) if m else None


def is_stale(root: Path) -> tuple[bool, str]:
    cur = current_block(root)
    fresh = build_block(root)
    if cur is None:
        return True, "docs/STATE.md:1: missing the projection block (run `meta checkpoint`)"
    if cur.strip() != fresh.strip():
        return True, "docs/STATE.md:1: the projection is stale vs. the facts (run `meta checkpoint`)"
    return False, "ok"


def refresh(root: Path) -> bool:
    """Rewrites the block in STATE.md (inserts it before the first `## ` if absent). Returns True if
    it changed. Does NOT reseal (the caller does that, via doc-sync)."""
    state = Path(root) / "docs" / "STATE.md"
    text = state.read_text(encoding="utf-8")
    fresh = build_block(root)
    matches = list(BLOCK_RE.finditer(text))
    if matches:
        # Replace the FIRST block in place; drop any further block(s) entirely. Handles the common
        # case (exactly one match) unchanged, and self-heals a stray duplicate — e.g. the legacy
        # Spanish marker and a fresh English one briefly coexisting across the START-text migration.
        pieces = [text[: matches[0].start()], fresh]
        prev_end = matches[0].end()
        for m in matches[1:]:
            pieces.append(text[prev_end: m.start()].rstrip("\n"))
            prev_end = m.end()
        pieces.append(text[prev_end:])
        new = re.sub(r"\n{3,}", "\n\n", "".join(pieces))
    else:
        m = re.search(r"^## ", text, re.MULTILINE)
        if m:
            new = text[: m.start()] + fresh + "\n\n" + text[m.start():]
        else:
            new = text.rstrip() + "\n\n" + fresh + "\n"
    if new == text:
        return False
    state.write_text(new, encoding="utf-8")
    return True
