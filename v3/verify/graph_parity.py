#!/usr/bin/env python3
"""Does the PORTED code-graph (`v3.graph`) reproduce v2's structural + quality metrics, at a pinned
commit — over an oracle whose whole POINT is the RED cases it also carries?

    python3 -m v3.verify.graph_parity                              # the gate
    V3_GRAPH_PARITY_SABOTAGE=1 python3 -m v3.verify.graph_parity   # the red side; must ALSO exit 0

THE OUTER ORACLE IS READ AT A COMMIT (ADR-031 §2.1): `v3/oracle_ref.json` names the pinned ref v2
was walked at. This gate's INNER fixture (`docs/spec/fixtures/graph-metrics-vectors.json`) is
generated BY this increment (`tools/gen_graph_metrics_vectors.py`), so — like `check-argv-vectors.json`
and `spec-validation-vectors.json` before it — it has no existence at `oracle_ref` to `git show` (that
commit predates it by construction). Reading it from disk is the honest move for THIS artifact, and
the ref-binding law is enforced the same way `kinds_parity`/`spec_parity` do it: the fixture's own
`oracle_ref` field must equal `v3/oracle_ref.json`'s pinned value, and a read at a nonexistent ref
(40 zeros) must FAIL (LOCK #2, exercised every run) — a read that merely opened whatever file happens
to be on disk would succeed no matter which ref it was asked for.

SELF-CONTAINED, NO GIT AT VERIFY TIME (contract point 7). Unlike `gate_census` (deleted at
V3-EXTRACT-OBLIGATIONS), this module holds NO oracle-reader exemption and does not materialise the
ref itself: the fixture generator already did
that once, and embeds every real file's raw `source` text in the fixture (the same move
`spec-validation-vectors.json` makes with `spec_yaml`). This gate rebuilds the declared input tree from
that embedded text into a throwaway directory and runs the PORTED `v3.graph.build`/`v3.graph.quality`
over it — so it compares against the FIXTURE, never against a live v2, and keeps working over a tree
that no longer contains `the v2 substrate` at all.

WHAT IS COMPARED, three groups:
  1. STRUCTURAL — the declared input set is `fixture["input_root"]` (v2's own `graph/`
     package at the ref, 15 files/~2026 LOC — DELIBERATELY broader than the 5 modules this increment
     ports, so the comparison proves the ported measurement code generalises rather than being fitted
     to its own source). For every file: `loc`, `imports` (module-level only), `function_count`, and
     `per_function_loc` (every function/method, any nesting depth) must match exactly. The full
     detected import-cycle list over this real input must match too (expected empty — the substrate is
     clean; the interesting cycle cases are RED, group 3).
  2. QUALITY — the same graph, v2's default `Thresholds`, `file_violations` must match exactly
     (expected empty, same reasoning).
  3. RED — the point. Three cases, each rebuilt from its own embedded synthetic/fixture source:
       (a) `tests/fixtures/quality/monolith_shaped.py` (v2's own committed negative-test fixture,
           carried here as DATA, never as code) must still trip >=1 violation.
       (b) a synthetic two-file MUTUAL module-level import must still be detected as a cycle.
       (c) a synthetic pair where the back-edge is a DEFERRED (function-scoped) import must still NOT
           be reported as a cycle — v2's own subtlety (cycle detection counts only module-level
           imports; a function-scoped import is a decoupling idiom, not a dependency edge). This
           negative control is checked in BOTH modes (nothing to "raise the threshold on" for an
           absence-of-cycle claim) — like LOCK #2's ref-binding check, its value is in running always.

LOCK #1: zero structural vectors, or zero RED vectors, is RED — never a vacuous green. An oracle with
no failure case in it cannot prove a monolith or a cycle detector actually has teeth (this is why
group 3 exists at all: (1)+(2) passing over clean code alone proves nothing).

SABOTAGE (contract point 5): raises the monolith case's thresholds to ~10**9 (nothing can violate) and
blinds the synthetic-cycle case's detector (pretends it found no cycle) — the two literal recipes the
brief names ("raise the thresholds ... or otherwise make the analysis blind"). Both perturb the INPUT
to an otherwise UNCHANGED comparison; if that comparison still passed, it was never measuring the red
side at all. Reported as `V3_GRAPH_PARITY_SABOTAGE (SABOTAGE)` — PASS means the deviations were caught.

SCOPE NOTE. `v3.graph.pbt_properties` is ported (with a stated cut — see its own docstring: P1 needs
`incremental.py`, INC-6 scope) but is NOT exercised by this gate — the brief scopes this gate's
comparisons to structural + quality + RED vectors, not to pbt_properties' own two-sided property
suite, which has no fixture of its own here.
"""
from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

from ..graph import build as v3_build
from ..graph import model as v3_model
from ..graph import quality as v3_quality
from ..kernel.report import Verdict

_V3 = Path(__file__).resolve().parent.parent
_ROOT = _V3.parent
_ORACLE_REF = _V3 / "oracle_ref.json"
_FIXTURE = _ROOT / "docs" / "spec" / "fixtures" / "graph-metrics-vectors.json"

_BOGUS_REF = "0" * 40

#: Sabotage recipe (a): thresholds so large nothing can ever violate — "raise the thresholds".
_BLIND_THRESHOLDS = v3_quality.Thresholds(max_file_loc=10 ** 9, max_funcs_per_file=10 ** 9,
                                          max_func_loc=10 ** 9)


def _oracle() -> dict:
    return json.loads(_ORACLE_REF.read_text(encoding="utf-8"))


def _load_fixture(ref: str) -> dict:
    """Read the fixture from disk (it has no history at `ref` to `git show` — see module docstring)
    and enforce the ref-binding the other way round: its OWN provenance stamp must name the SAME
    pinned commit, so a fixture built against a different or now-stale ref is caught rather than
    silently compared against the wrong past."""
    if not _FIXTURE.exists():
        raise FileNotFoundError(f"{_FIXTURE}: not generated yet (tools/gen_graph_metrics_vectors.py)")
    fixture = json.loads(_FIXTURE.read_text(encoding="utf-8"))
    stamped = fixture.get("oracle_ref")
    if stamped != ref:
        raise ValueError(f"fixture stamps oracle_ref={stamped!r}, pinned ref is {ref!r} — "
                         f"regenerate with tools/gen_graph_metrics_vectors.py")
    return fixture


def _ref_binding_problems() -> list[str]:
    """LOCK #2. A working-tree read would succeed at any ref; this one must fail at a ref that
    cannot be the pinned commit (40 zeros), proving the fixture read is bound to the ref it is
    handed, not to "whatever is on disk"."""
    try:
        _load_fixture(_BOGUS_REF)
    except (FileNotFoundError, ValueError):
        return []
    return ["_load_fixture succeeded at a nonexistent ref (40 zeros) — the fixture read is not "
            "ref-bound, it just opens whatever is on disk"]


def _write_tree(root: Path, files: dict[str, str]) -> None:
    for relpath, source in files.items():
        path = root / relpath
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source, encoding="utf-8")


def _violation_to_dict(v) -> dict:
    return {"relpath": v.relpath, "metric": v.metric, "value": v.value, "limit": v.limit}


def _structural_problems(fixture: dict) -> tuple[list[str], dict]:
    """Groups 1+2: rebuild the declared input tree from embedded source, run the PORTED code, compare
    every recorded metric exactly."""
    problems: list[str] = []
    files = fixture["structural"]["files"]
    counts = {"structural_files": len(files), "real_cycles": len(fixture["structural"]["cycles"]),
              "quality_violations": len(fixture["quality"]["violations"])}
    if not files:
        problems.append("zero structural vectors — a green here would be vacuous (Lock #1)")
        return problems, counts

    try:
        with tempfile.TemporaryDirectory(prefix="v3-graph-parity-struct-") as tmp:
            tmp = Path(tmp)
            _write_tree(tmp, {f["relpath"]: f["source"] for f in files})
            graph, fragments = v3_build.build_code_graph(tmp, roots=(fixture["input_root"],))

            want_relpaths = sorted(f["relpath"] for f in files)
            if sorted(fragments) != want_relpaths:
                problems.append(f"discover_python found {sorted(fragments)}, fixture recorded "
                                f"{want_relpaths}")

            for f in files:
                fid = f"File:{f['relpath']}"
                node = graph.node(fid)
                if node is None:
                    problems.append(f"{f['relpath']}: no File node in the ported graph")
                    continue
                got_loc = int(node.attrs.get("loc", -1))
                if got_loc != f["loc"]:
                    problems.append(f"{f['relpath']}: loc={got_loc}, fixture says {f['loc']}")
                got_imports = list(node.attrs.get("imports", []))
                if got_imports != f["imports"]:
                    problems.append(f"{f['relpath']}: imports={got_imports}, fixture says "
                                    f"{f['imports']}")

                syms = [graph.node(e.src) for e in graph.in_edges(fid, v3_model.EdgeKind.DEFINED_IN)]
                got_funcs = sorted(
                    ({"qualname": s.attrs["qualname"], "loc": int(s.attrs["loc"])} for s in syms
                     if s and s.attrs.get("symtype") == "function"),
                    key=lambda d: d["qualname"],
                )
                want_funcs = sorted(f["per_function_loc"], key=lambda d: d["qualname"])
                if got_funcs != want_funcs:
                    problems.append(f"{f['relpath']}: per-function LOC mismatch\n"
                                    f"    got:  {got_funcs}\n    want: {want_funcs}")
                if len(got_funcs) != f["function_count"]:
                    problems.append(f"{f['relpath']}: function_count={len(got_funcs)}, fixture says "
                                    f"{f['function_count']}")
                got_classes = sum(1 for s in syms if s and s.attrs.get("symtype") == "class")
                if got_classes != f.get("class_count", got_classes):
                    problems.append(f"{f['relpath']}: class_count={got_classes}, fixture says "
                                    f"{f['class_count']}")

            got_cycles = v3_quality.import_cycles(graph)
            want_cycles = fixture["structural"]["cycles"]
            if got_cycles != want_cycles:
                problems.append(f"real-substrate cycles={got_cycles}, fixture says {want_cycles}")

            th = v3_quality.Thresholds.from_dict(fixture["quality"]["thresholds"])
            got_viol = [_violation_to_dict(v) for v in v3_quality.file_violations(graph, th)]
            want_viol = fixture["quality"]["violations"]
            if got_viol != want_viol:
                problems.append(f"quality violations={got_viol}, fixture says {want_viol}")
    except Exception as exc:  # noqa: BLE001 — a broken port raising IS a parity failure, not a crash
        problems.append(f"structural comparison raised {exc!r}")

    return problems, counts


def _canon(value) -> str:
    """A total order for dict-shaped records: canonical JSON. Used only for sorting two lists into
    a comparable order — never for equality, which stays structural."""
    return json.dumps(value, sort_keys=True, ensure_ascii=False)


def _red_problems(fixture: dict, *, sabotage: bool) -> tuple[list[str], dict]:
    """Group 3 — the RED cases, which are the point. Each is rebuilt in its own throwaway tree."""
    problems: list[str] = []
    red = fixture.get("red", {})
    counts = {"red_vectors": len(red)}
    if not red:
        problems.append("zero RED vectors — never a vacuous green (Lock #1)")
        return problems, counts

    try:
        # ── (a) the committed monolith fixture must still trip its violation ────────────────────
        mono = red["monolith"]
        with tempfile.TemporaryDirectory(prefix="v3-graph-parity-mono-") as tmp:
            tmp = Path(tmp)
            _write_tree(tmp, {mono["relpath"]: mono["source"]})
            th = _BLIND_THRESHOLDS if sabotage else v3_quality.Thresholds.from_dict(
                fixture["quality"]["thresholds"])
            # `sorted` needs a key here: these are dicts, and dicts are not orderable. Sorting them
            # bare raised TypeError, which this gate reported as a deviation rather than swallowing
            # — so the RED case never actually ran while the gate stayed loudly red. Canonical JSON
            # is the ordering, so the comparison is on CONTENT and not on dict insertion order.
            got = sorted((_violation_to_dict(v)
                          for v in v3_quality.evaluate_file(tmp, mono["relpath"], th)), key=_canon)
            want = sorted(mono["violations"], key=_canon)
            if not got:
                problems.append("monolith RED case produced ZERO violations"
                                + (" under sabotage thresholds" if sabotage else
                                   " — a vacuous red case proves nothing"))
            elif got != want:
                problems.append(f"monolith violations={got}, fixture says {want}")

        # ── (b) a synthetic mutual module-level import must be detected as a cycle ───────────────
        cyc = red["synthetic_cycle"]
        with tempfile.TemporaryDirectory(prefix="v3-graph-parity-cycle-") as tmp:
            tmp = Path(tmp)
            _write_tree(tmp, cyc["files"])
            graph, _ = v3_build.build_code_graph(tmp, roots=("src",))
            got_cycles = [] if sabotage else v3_quality.import_cycles(graph)   # "blind the analysis"
            want_cycles = cyc["expected_cycles"]
            if not got_cycles:
                problems.append("synthetic-cycle RED case detected NO cycle"
                                + (" (sabotage: analysis blinded)" if sabotage else ""))
            elif got_cycles != want_cycles:
                problems.append(f"synthetic-cycle detected {got_cycles}, fixture says {want_cycles}")

        # ── (c) a deferred (function-scoped) import must NOT be a cycle — always checked ────────
        defer = red["deferred_import_not_cycle"]
        with tempfile.TemporaryDirectory(prefix="v3-graph-parity-defer-") as tmp:
            tmp = Path(tmp)
            _write_tree(tmp, defer["files"])
            graph, _ = v3_build.build_code_graph(tmp, roots=("src",))
            got_cycles = v3_quality.import_cycles(graph)
            want_cycles = defer["expected_cycles"]
            if got_cycles != want_cycles:
                problems.append(f"deferred-import case reports cycles={got_cycles}, v2 recorded "
                                f"{want_cycles} — a module-level-only detector must not count a "
                                f"function-scoped import")
    except Exception as exc:  # noqa: BLE001 — a broken port raising IS a parity failure, not a crash
        problems.append(f"RED-case comparison raised {exc!r}")

    return problems, counts


def check(ref: str, *, sabotage: bool = False) -> tuple[list[str], dict]:
    """The LAW: rebuild the declared input from the fixture's embedded source, run the PORTED code,
    compare every recorded metric — structural, quality, and (the point) the RED cases."""
    problems: list[str] = []
    problems.extend(_ref_binding_problems())

    fixture = _load_fixture(ref)
    struct_problems, struct_counts = _structural_problems(fixture)
    red_problems, red_counts = _red_problems(fixture, sabotage=sabotage)
    problems.extend(struct_problems)
    problems.extend(red_problems)

    return problems, {**struct_counts, **red_counts}


def main(argv: list[str]) -> int:
    if argv:
        return Verdict("v3-graph-parity", 2, f"takes no arguments; got {argv!r}").emit()

    ref = _oracle()["oracle_ref"]

    if os.environ.get("V3_GRAPH_PARITY_SABOTAGE") == "1":
        problems, counts = check(ref, sabotage=True)
        if problems:
            return Verdict("v3-graph-parity (SABOTAGE)", 0,
                           f"the blinded RED cases were detected: {len(problems)} deviation(s)",
                           counts=counts).emit()
        return Verdict("v3-graph-parity (SABOTAGE)", 1,
                       "GATE DECORATIVO: raised thresholds / a blinded cycle detector still passed",
                       counts=counts).emit()

    problems, counts = check(ref)
    if problems:
        return Verdict("v3-graph-parity", 1, f"{len(problems)} deviation(s) @ {ref[:12]}",
                       counts=counts, failures=tuple(problems)).emit()
    return Verdict("v3-graph-parity", 0,
                   f"{counts['structural_files']} file(s) @ {ref[:12]}: "
                   f"{counts['real_cycles']} real cycle(s), {counts['quality_violations']} quality "
                   f"violation(s) reproduced; {counts['red_vectors']} RED case(s) bite", counts=counts
                   ).emit()


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
