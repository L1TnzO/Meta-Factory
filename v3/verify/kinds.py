"""kinds — the frozen 29 check-KIND vocabulary and its argv resolution, PORTED from v2.

WHAT THIS IS. v2's single source is `metafactory/verify/checks/registry.py` (under v2's `src/`
tree): the `KINDS` tuple
(D-3, VOCAB-FREEZE) and `resolve_check(check, ctx, station, subst) -> list[str]`, a pure mapping from
a station's declared `{name, kind, ...}` check dict to the subprocess argv the seed verifier runs
(cwd == ctx.root, exit 0 == pass). This module TRANSCRIBES that behaviour without importing it
(ADR-031 §Consequences, `v3.verify.import_boundary`): the kernel is ported, never referenced.

WHERE THE ORACLE LIVES. `docs/spec/fixtures/check-argv-vectors.json`, generated by
`tools/gen_check_argv_vectors.py` (v2-side, free to import `metafactory`) by walking every committed
station YAML AT `v3/oracle_ref.json`'s `oracle_ref` commit and calling v2's real `resolve_check`. The
two-sided gate that reproduces every vector against THIS module is `v3.verify.kinds_parity`.

`ctx` IS UNUSED — transcribed faithfully: v2's `resolve_check` never reads it either (grep the
source; the parameter exists for signature symmetry with the caller, not for any branch below). This
looked like it might be an oversight, so it is called out here rather than silently dropped: dropping
it would change the *signature* this increment is asked to port, not just its behaviour.

`docs_check` ALWAYS resolves against "wherever this codebase's own root is", ignoring both `subst`
and the calling `station`/`ctx` entirely (v2: `str(repo_root())`, unconditional) — surprising for a
kind that sounds station-scoped, but that is v2's actual behaviour and it is reproduced as-is via
`_this_repo_root()` below (see THE PORT RULE for why that helper exists rather than an import).
`blast_radius`/`scenario_corpus` share the same "fall back to my own root" shape when `subst` omits
`meta_root`.

THE PORT RULE — SAME ARGV, HEAD SEGMENT SWAPPED (documented here because parity is the contract, and
a rule that is not written down is a rule nobody agreed to). Of the 29 kinds, 24 hardcode, INSIDE
v2's own `resolve_check`, a dotted executor-module target at argv[2] rooted in v2's own package (a
`...verify.checks.<X>` submodule, or the bare `...spec.cli` / `...cli` entrypoint — read at
`v3/oracle_ref.json`'s pinned commit, not invented). Those are not values THIS module is free to omit:
for these 24 kinds, the executor **is** the mapping — `resolve_check`'s entire job is kind -> argv,
and the module that runs a kind's check is the load-bearing element of that argv. The port rule is
mechanical and invents nothing: **same argv, first dotted segment swapped from the v2 package name to
`v3`.** So v2's `metafactory.verify.checks.artifact_contains` becomes `v3.verify.checks.artifact_contains`,
`metafactory.spec.cli` becomes `v3.spec.cli`, and `metafactory.cli` becomes `v3.cli` — every other
segment, and every other argv position, is unchanged. Applying that rule to each of the 24 kinds
produces the literals hardcoded below directly (there is nothing left to compute at import time, and
nothing here ever spells the v2 package name — `v3.verify.import_boundary` rule 3 forbids it, and
there is no need to earn an exemption when the swapped result is a plain v3-rooted string). The other
five kinds (`py_compile`, `import_runs`, `pytest`, `isolation`, `command`) either name a real
third-party/stdlib module that is not v2's substrate (`py_compile`, `pytest`) and so needs no swap, or
carry no module target at all (`import_runs` uses `-c`, `command` is a pure pass-through of check
DATA).

`v3.verify.checks.<name>` does not exist as a package yet for most of these 24 names — that is
intended: a later phase of this increment ports those executor BODIES, and this argv is what says
where they must live. `v3.spec.cli` and `v3.cli` are the same story for the three kinds that route
through an entrypoint rather than a per-kind module.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

PY = sys.executable

_PLACEHOLDER = re.compile(r"\{\{\s*([a-zA-Z0-9_]+)\s*\}\}")

# ── the swapped v3 executor targets — see THE PORT RULE above. Every value here is the RESULT of
# applying "first dotted segment: v2 package -> v3" to v2's own hardcoded string; none of them ever
# spells the v2 package name. ──────────────────────────────────────────────────────────────────────
_CHECKS = "v3.verify.checks"   # was `metafactory.verify.checks` in v2
_SPEC_CLI = "v3.spec.cli"      # was `metafactory.spec.cli` in v2
_CLI = "v3.cli"                # was `metafactory.cli` in v2

# ── FROZEN vocabulary (D-3, VOCAB-FREEZE) — mirror of `registry.KINDS`, same 29 names, same order. ──
KINDS = (
    "py_compile", "import_runs", "artifact_contains", "spec_validate",
    "rtm_closure", "design_review", "pytest", "isolation", "docs_check", "command",
    "column_selftest", "column_full", "bus_bounded", "product_run", "boundary_survives",
    "rtm_rederive", "rtm_tree", "clean_runner", "agent_shadow", "product_env", "command_runs",
    "infra_up", "mcp_tools", "eval_gate", "eval_floor", "live_run", "blast_radius", "scenario_corpus",
    "products_rederive",
)


def _render_text(text: str, subst: dict) -> str:
    """Transcribed from v2's `codegen.renderer.render_text`: substitute `{{var}}` from `subst`; an
    unresolved placeholder is a KeyError, not a silent pass-through (the caller supplied bad data)."""

    def repl(m: "re.Match[str]") -> str:
        key = m.group(1)
        if key not in subst:
            raise KeyError(f"template placeholder {{{{{key}}}}} has no value in subst")
        return str(subst[key])

    return _PLACEHOLDER.sub(repl, text)


def _s(value, subst):
    """Transcribed from v2's `registry._s`: substitute a string, or recurse into a list/tuple."""
    if isinstance(value, str):
        return _render_text(value, subst)
    if isinstance(value, (list, tuple)):
        return [_s(v, subst) for v in value]
    return value


def _this_repo_root() -> Path:
    """Structural analogue of v2's `_seed.repo_root()` — NOT an import of it. Both v2's `_seed.py`
    (two directories under v2's `src/` tree) and this file (`v3/verify/kinds.py`, two directories
    under `v3/`) sit exactly two directories below their repository's root, so the same
    `parents[2]` arithmetic lands on the same directory without this module ever depending on the
    v2 package existing."""
    return Path(__file__).resolve().parents[2]


def resolve_check(check: dict, ctx, station, subst: dict) -> list[str]:
    """`check` -> argv, cwd == ctx.root at run time (ctx unused here, see module docstring)."""
    kind = check.get("kind")

    if kind == "py_compile":
        files = _s(check["files"], subst)
        return [PY, "-m", "py_compile", *files]
    if kind == "import_runs":
        return [PY, "-c", _s(check["code"], subst)]
    if kind == "artifact_contains":
        return [PY, "-m", f"{_CHECKS}.artifact_contains",
                _s(check["file"], subst), _s(check["marker"], subst)]
    if kind == "spec_validate":
        return [PY, "-m", _SPEC_CLI, "validate", _s(check["spec"], subst)]
    if kind == "rtm_closure":
        return [PY, "-m", _SPEC_CLI, "rtm-closure", _s(check["spec"], subst)]
    if kind == "design_review":
        return [PY, "-m", _SPEC_CLI, "design-review", _s(check["spec"], subst)]
    if kind == "pytest":
        return [PY, "-m", "pytest", "-q", _s(check["path"], subst)]
    if kind == "isolation":
        return [PY, "-m", "pytest", "-q", _s(check.get("path", "tests/test_isolation.py"), subst)]
    if kind == "docs_check":
        return [PY, "-m", f"{_CHECKS}.docs_check", str(_this_repo_root())]
    if kind == "command":
        return _s(check["cmd"], subst)
    if kind == "column_selftest":
        return [PY, "-m", f"{_CHECKS}.column_selftest", str(subst.get("factory_root", "."))]
    if kind == "column_full":
        return [PY, "-m", f"{_CHECKS}.column_full", str(subst.get("factory_root", "."))]
    if kind == "command_runs":
        return [PY, "-m", f"{_CHECKS}.command_runs", str(subst.get("factory_root", "."))]
    if kind == "bus_bounded":
        return [PY, "-m", f"{_CHECKS}.bus_bounded", str(subst.get("max_lines", 10))]
    if kind == "product_run":
        return [PY, "-m", _CLI, "product-run", "--factory", str(subst.get("slug", ""))]
    if kind == "boundary_survives":
        return [PY, "-m", f"{_CHECKS}.boundary_survives",
                str(subst.get("factory_root", ".")), str(subst.get("meta_root", "")),
                str(subst.get("spec_path", "factory.spec.yml"))]
    if kind == "rtm_rederive":
        return [PY, "-m", f"{_CHECKS}.rtm_rederive",
                str(subst.get("factory_root", ".")), str(subst.get("meta_root", "")),
                str(subst.get("spec_path", "factory.spec.yml"))]
    if kind == "rtm_tree":
        return [PY, "-m", f"{_CHECKS}.rtm_tree",
                str(subst.get("factory_root", ".")), str(subst.get("meta_root", "")),
                str(subst.get("spec_path", "factory.spec.yml"))]
    if kind == "clean_runner":
        return [PY, "-m", f"{_CHECKS}.clean_runner",
                str(subst.get("factory_root", ".")), str(subst.get("meta_root", "")),
                str(subst.get("spec_path", "factory.spec.yml"))]
    if kind == "products_rederive":
        return [PY, "-m", f"{_CHECKS}.products_rederive",
                str(subst.get("factory_root", ".")), str(subst.get("meta_root", ""))]
    if kind == "agent_shadow":
        return [PY, "-m", f"{_CHECKS}.agent_shadow",
                str(subst.get("factory_root", ".")), str(subst.get("meta_root", "")),
                str(subst.get("spec_path", "factory.spec.yml"))]
    if kind == "product_env":
        return [PY, "-m", f"{_CHECKS}.product_env",
                _s(check.get("workdir", "."), subst),
                json.dumps(_s(check.get("bootstrap", []), subst)),
                json.dumps(_s(check["cmd"], subst))]
    if kind == "infra_up":
        argv = [PY, "-m", f"{_CHECKS}.infra_up",
                _s(check.get("workdir", "."), subst),
                json.dumps(_s(check.get("up", []), subst)),
                json.dumps(_s(check["proof"], subst)),
                json.dumps(_s(check.get("down", []), subst)),
                json.dumps(_s(check.get("bootstrap", []), subst))]
        if check.get("timeout"):
            argv.append(str(check["timeout"]))
        return argv
    if kind == "mcp_tools":
        return [PY, "-m", f"{_CHECKS}.mcp_tools",
                _s(check.get("workdir", "."), subst),
                json.dumps(_s(check["prove"], subst)),
                json.dumps(_s(check.get("tools", []), subst))]
    if kind == "eval_gate":
        return [PY, "-m", f"{_CHECKS}.eval_gate",
                _s(check.get("workdir", "."), subst),
                json.dumps(_s(check["scorer"], subst)),
                _s(check["output"], subst),
                _s(check["degraded"], subst),
                json.dumps(_s(check["thresholds"], subst)),
                json.dumps(_s(check.get("bootstrap", []), subst))]
    if kind == "eval_floor":
        return [PY, "-m", f"{_CHECKS}.eval_floor",
                _s(check.get("workdir", "."), subst),
                json.dumps(_s(check["command"], subst)),
                _s(check["evidence"], subst),
                _s(check["degraded"], subst),
                _s(check["thresholds"], subst),
                json.dumps(_s(check.get("bootstrap", []), subst))]
    if kind == "live_run":
        return [PY, "-m", f"{_CHECKS}.live_run",
                _s(check.get("workdir", "."), subst),
                json.dumps(_s(check.get("run", []), subst)),
                _s(check["output"], subst),
                _s(check["degraded"], subst),
                json.dumps(_s(check.get("properties", []), subst)),
                json.dumps(_s(check.get("scorer", []), subst)),
                json.dumps(_s(check.get("thresholds", {}), subst)),
                _s(check.get("provider_env", ""), subst),
                json.dumps(_s(check.get("bootstrap", []), subst))]
    if kind == "blast_radius":
        meta_root = str(subst.get("meta_root", _this_repo_root()))
        baseline = _s(check.get("baseline", "baseline_verdicts.json"), subst)
        return [PY, "-m", f"{_CHECKS}.blast_radius", meta_root, baseline]
    if kind == "scenario_corpus":
        meta_root = str(subst.get("meta_root", _this_repo_root()))
        argv = [PY, "-m", f"{_CHECKS}.scenario_corpus", meta_root]
        if check.get("corpus"):
            argv.append(_s(check["corpus"], subst))
        return argv

    raise ValueError(f"unknown check kind {kind!r} in station {station.id} (known: {KINDS})")
