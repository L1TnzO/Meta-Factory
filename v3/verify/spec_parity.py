#!/usr/bin/env python3
"""Does the PORTED spec model/loader/validator (`v3.spec`) reproduce v2's decisions, at a pinned
commit — over an oracle that contains FAILURES as well as successes?

    python3 -m v3.verify.spec_parity                              # the gate
    V3_SPEC_PARITY_SABOTAGE=1 python3 -m v3.verify.spec_parity    # the red side; must ALSO exit 0

THE OUTER ORACLE IS READ AT A COMMIT (ADR-031 §2.1): `v3/oracle_ref.json` names the pinned ref v2 was
walked at. This gate's INNER fixture (`docs/spec/fixtures/spec-validation-vectors.json`) is different
from `proof-sha-vectors.json`: it is generated BY this increment
(`tools/gen_spec_validation_vectors.py`), so — like `check-argv-vectors.json` before it — it has no
existence at `oracle_ref` to `git show` (that commit predates it by construction). Reading it from disk
is the honest move for THIS artifact, and the ref-binding law (ADR-031 §2.1) is enforced the same way
`v3.verify.kinds_parity` does it: the fixture's own `oracle_ref` field must equal `v3/oracle_ref.json`'s
pinned value, and a read at a nonexistent ref (40 zeros) must FAIL (LOCK #2, exercised every run) — a
read that merely opened whatever file happens to be on disk would succeed no matter which ref it was
asked for.

WHAT IS COMPARED. Every vector embeds its OWN full `spec_yaml` (so this gate never depends on the
working tree's `factories/*/factory.spec.yml` staying byte-identical to what v2 decided at the ref):

  1. DECISION PARITY, both directions — every `accept_vector` must come back `valid` under
     `v3.spec.{load_spec,validate}`, and every `reject_vector` must come back `invalid`. A vector that
     flips either way is a parity failure.
  2. REJECTION LOCALITY — each `reject_vector` records the offending IDENTIFIER v2's message named
     (station id / requirement id / field name); v3's own problem list must name that SAME identifier
     somewhere (message wording is free, English-authored here; the identifier is not).
  3. LOADER PARITY — the accept vectors also carry a STRUCTURAL DIGEST (station ids in order,
     per-station depends_on/tier/activation/status/check-counts, capability/requirement ids, which
     machinery sections are present); the ported loader must reproduce it exactly, so a port that
     quietly drops a field is caught even though it would not change the accept/reject decision.
  4. COVERAGE, counted and printed apart from correctness: how many of v2's validator rules have a
     mutant in the fixture (`rule_inventory`), and which (if any) do not (`rules_without_mutant`).

LOCK #1: zero vectors, or zero reject-vectors, is RED — never a vacuous green. An oracle with no
failures in it cannot prove a validator rejects anything (this is the whole point of this port: a
validator that accepts everything passes an accept-only suite perfectly).

SABOTAGE: makes the ported `validator.validate` permissive (always returns no problems — v2's failure
mode this design exists to prevent) and asserts every `reject_vector` is now caught as a deviation.
This is the exact tooth Lock #1's reasoning describes made concrete: if the suite still passed with a
gutted validator, it was never measuring rejection at all.

SCOPE NOTE. `v3.spec.design`/`v3.spec.primitives`/`v3.spec.cli`'s `design-review` command are ported
(V3-INC4, Phase 4) to complete the CLI surface `v3.verify.kinds` already routes to, but this port's
brief scopes the oracle's RULE INVENTORY to `validator.py` only — `design.py`'s own decisions are NOT
vectors in this fixture and get their dedicated proof under the `design_eval` gate (a later phase).
"""
from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

from ..kernel.report import Verdict
from ..spec import loader as spec_loader
from ..spec import validator as spec_validator

_V3 = Path(__file__).resolve().parent.parent
_ROOT = _V3.parent
_ORACLE_REF = _V3 / "oracle_ref.json"
_FIXTURE = _ROOT / "docs" / "spec" / "fixtures" / "spec-validation-vectors.json"

_BOGUS_REF = "0" * 40


def _oracle() -> dict:
    return json.loads(_ORACLE_REF.read_text(encoding="utf-8"))


def _load_fixture(ref: str) -> dict:
    """Read the fixture from disk (it has no history at `ref` to `git show` — see module docstring)
    and enforce the ref-binding the other way round: its OWN provenance stamp must name the SAME
    pinned commit, so a fixture built against a different or now-stale ref is caught rather than
    silently compared against the wrong past."""
    if not _FIXTURE.exists():
        raise FileNotFoundError(f"{_FIXTURE}: not generated yet (tools/gen_spec_validation_vectors.py)")
    fixture = json.loads(_FIXTURE.read_text(encoding="utf-8"))
    stamped = fixture.get("oracle_ref")
    if stamped != ref:
        raise ValueError(f"fixture stamps oracle_ref={stamped!r}, pinned ref is {ref!r} — "
                         f"regenerate with tools/gen_spec_validation_vectors.py")
    return fixture


def _ref_binding_problems() -> list[str]:
    """LOCK #2. A working-tree read would succeed at any ref; this one must fail at a ref that cannot
    be the pinned commit (40 zeros), proving the fixture read is bound to the ref it is handed, not to
    "whatever is on disk"."""
    try:
        _load_fixture(_BOGUS_REF)
    except (FileNotFoundError, ValueError):
        return []
    return ["_load_fixture succeeded at a nonexistent ref (40 zeros) — the fixture read is not "
            "ref-bound, it just opens whatever is on disk"]


def _station_digest(station) -> dict:
    return {
        "id": station.id, "activation": station.activation, "status": station.status,
        "tier": station.tier, "depends_on": list(station.depends_on),
        "builds_count": len(station.builds), "checks_count": len(station.checks),
        "proof_checks_count": len(station.proof_checks),
    }


def _loader_digest(spec) -> dict:
    """MUST match `tools/gen_spec_validation_vectors.py`'s `_loader_digest` shape exactly — this is
    the structural-parity contract (§3), not merely a convenience mirror."""
    return {
        "slug": spec.slug, "name": spec.name, "maturity": spec.maturity, "produces": spec.produces,
        "station_ids": [s.id for s in spec.stations],
        "stations": [_station_digest(s) for s in spec.stations],
        "capability_ids": [c.id for c in spec.capabilities],
        "requirement_ids": [r.id for r in spec.requirements],
        "machinery_present": {
            "harness": bool(spec.machinery.harness), "mcp": bool(spec.machinery.mcp),
            "infra": bool(spec.machinery.infra),
        },
    }


def _write_and_load(spec_yaml: str, workdir: Path, name: str):
    path = workdir / name
    path.write_text(spec_yaml, encoding="utf-8")
    return spec_loader.load_spec(path)


def check(ref: str, *, sabotage: bool = False) -> tuple[list[str], dict]:
    """The LAW: recompute every vector with the ported loader/validator, compare to the oracle."""
    problems: list[str] = []
    problems.extend(_ref_binding_problems())

    fixture = _load_fixture(ref)
    accept_vectors = fixture.get("accept_vectors", [])
    reject_vectors = fixture.get("reject_vectors", [])
    rule_inventory = fixture.get("rule_inventory", [])
    rules_without_mutant = fixture.get("rules_without_mutant", [])

    counts = {
        "accept_vectors": len(accept_vectors), "reject_vectors": len(reject_vectors),
        "rules_total": len(rule_inventory),
        "rules_with_mutant": sum(1 for r in rule_inventory if r.get("has_mutant")),
        "rules_without_mutant": len(rules_without_mutant),
    }

    if not accept_vectors and not reject_vectors:
        problems.append("zero vectors at the oracle ref — a green here would be vacuous (Lock #1)")
        return problems, counts
    if not reject_vectors:
        problems.append("zero REJECT vectors — an oracle with no failures cannot prove a validator "
                        "rejects anything (Lock #1)")
        return problems, counts

    with tempfile.TemporaryDirectory(prefix="v3-spec-parity-") as tmp:
        workdir = Path(tmp)

        for i, vec in enumerate(accept_vectors):
            origin = vec.get("origin", f"accept[{i}]")
            try:
                spec = _write_and_load(vec["spec_yaml"], workdir, f"accept_{i:02d}.yml")
            except Exception as exc:  # noqa: BLE001 — a load failure IS a parity failure here
                problems.append(f"{origin}: v3 load_spec raised {exc!r}")
                continue
            got_problems = spec_validator.validate(spec)
            got_decision = "valid" if not got_problems else "invalid"
            if got_decision != vec.get("decision"):
                problems.append(f"{origin}: decision mismatch — v2 said {vec.get('decision')!r}, "
                                f"v3 said {got_decision!r} ({got_problems!r})")
                continue

            got_digest = _loader_digest(spec)
            want_digest = vec.get("loader_digest")
            if got_digest != want_digest:
                problems.append(f"{origin}: loader digest mismatch\n    got:  {got_digest}\n"
                                f"    want: {want_digest}")

        for i, vec in enumerate(reject_vectors):
            rule_id = vec.get("rule_id", f"reject[{i}]")
            try:
                spec = _write_and_load(vec["spec_yaml"], workdir, f"reject_{i:02d}.yml")
            except Exception as exc:  # noqa: BLE001
                problems.append(f"{rule_id}: v3 load_spec raised {exc!r}")
                continue
            got_problems = spec_validator.validate(spec)
            if not got_problems:
                problems.append(f"{rule_id}: v3 ACCEPTED a spec v2 rejects "
                                f"(mutation: {vec.get('description')})")
                continue
            identifier = vec.get("offending_identifier", "")
            joined = "\n".join(got_problems)
            if identifier and identifier not in joined:
                problems.append(f"{rule_id}: rejected, but v3's problems never name the offending "
                                f"identifier {identifier!r} — got: {got_problems!r}")

    return problems, counts


def main(argv: list[str]) -> int:
    if argv:
        return Verdict("v3-spec-parity", 2, f"takes no arguments; got {argv!r}").emit()

    ref = _oracle()["oracle_ref"]

    if os.environ.get("V3_SPEC_PARITY_SABOTAGE") == "1":
        original = spec_validator.validate
        spec_validator.validate = lambda spec: []   # v2's failure mode: accept everything
        try:
            problems, counts = check(ref, sabotage=True)
        finally:
            spec_validator.validate = original
        if problems:
            return Verdict("v3-spec-parity (SABOTAGE)", 0,
                           f"a permissive validator was caught: {len(problems)} deviation(s)",
                           counts=counts).emit()
        return Verdict("v3-spec-parity (SABOTAGE)", 1,
                       "GATE DECORATIVO: a validator that accepts everything still passed",
                       counts=counts).emit()

    problems, counts = check(ref)
    if problems:
        return Verdict("v3-spec-parity", 1,
                       f"{len(problems)} deviation(s) over {counts['accept_vectors']} accept + "
                       f"{counts['reject_vectors']} reject vector(s) @ {ref[:12]}",
                       counts=counts, failures=tuple(problems)).emit()
    return Verdict("v3-spec-parity", 0,
                   f"{counts['accept_vectors']} accept + {counts['reject_vectors']} reject vector(s) "
                   f"reproduce v2's decisions @ {ref[:12]}; "
                   f"{counts['rules_with_mutant']}/{counts['rules_total']} validator rule(s) covered "
                   f"by a mutant ({counts['rules_without_mutant']} without)",
                   counts=counts).emit()


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
